import { test, expect } from '@playwright/test';
import * as fs from 'fs';
import * as path from 'path';
import { expectSectionShots } from './section-shots';
import { AGGREGATE_PAGES } from './aggregate-pages';

// Scan-driven gallery coverage (doc/playwright-visual-test-guide.md §5).
//
// This spec discovers preview pages by SCANNING src/test/resources/web/*.zul at
// collection time, so a NEW component page is covered by a baseline screenshot the
// moment it is added — no edit to this file required. That closes the silent-gap
// problem of the hand-maintained screenshot.spec.ts.
//
// Each covered page gets one gallery screenshot per section of its `.z-p-8` wrapper
// (section-shots.ts); a page with no standard heading row keeps ONE shot of the wrapper. Richer
// state matrices (hover/focus/active) and computed-style guards stay in
// screenshot.spec.ts; this spec is the breadth layer, that one is the depth layer.
//
// Requires the preview app on ${PREVIEW_URL}
//   withjdk.sh 17 mvn test exec:java@preview-app

const WEB_DIR = path.resolve(__dirname, '../../main/webapp/web');

// Pages with a bespoke gallery block already in screenshot.spec.ts — skip here to
// avoid duplicate baselines. Their depth coverage (states) lives there.
const COVERED_ELSEWHERE = new Set([
  'button', 'textbox', 'checkbox', 'combobox', 'listbox', 'grid', 'datebox',
  'timebox', 'spinner', 'bandbox', 'selectbox', 'tabbox', 'tree', 'window', 'panel', 'toast',
]);

// Pages a static gallery screenshot can't meaningfully or stably capture.
const SKIP = new Set([
  // Aggregate pages (scripts/aggregate-pages.json): each component has its own page
  ...AGGREGATE_PAGES,
  // Non-visual primitives / structural / meta pages
   'area', 'html', 'iframe', 'imagemap', 
  'scrollbar',
  // Non-deterministic / hardware / external-resource / animated → flaky baselines
  'camera', 'barcodescanner', 'captcha', 'video', 'audio', 'fileupload', 'loading', 'loadingbar',
  // Auto-generated icon catalog (all Lucide icons) — a whole-page listing, not an ordinary
  // preview; regenerated by build:css. Also excluded from check-icon-coverage.sh.
  'icons-lucide'
]);

// Absolute per-section pixel budget, set from measured noise (tasks/marble-sectioned-gallery-pilot.md).
const SECTION_MAX_DIFF_PIXELS = 20;

// Sections that cannot be shot statically. The page says so itself for the carousel autoplay demo
// ("advances every 2s ... not part of any static-frame assertion, for visual confirmation only").
// The sizedByContent demos of the header pages end up in one of two states decided when the page
// loads, whatever happens afterwards (listbox-header measured 2026-10-18: 3 of 12 loads render
// "Super Long Product Name Here" cut by an ellipsis in a 225px cell, 9 of 12 render it whole in
// 228px; grid-header and tree-header show the same split). See tasks/marble-sectioned-gallery-pilot.md.
const SIZED_BY_CONTENT = /sizedByContent/i;
const UNSTABLE_SECTIONS: Record<string, RegExp | undefined> = {
  carousel: /^Autoplay/i,
  'grid-header': SIZED_BY_CONTENT,
  'listbox-header': SIZED_BY_CONTENT,
  'tree-header': SIZED_BY_CONTENT,
};

const pages = fs.readdirSync(WEB_DIR)
  .filter(f => f.endsWith('.zul'))
  .map(f => f.replace(/\.zul$/, ''))
  .filter(name => !COVERED_ELSEWHERE.has(name) && !SKIP.has(name))
  .sort();

test.describe('gallery', () => {
  for (const comp of pages) {
    test(comp, async ({ page }) => {
      await page.goto(`/${comp}.zul`, { waitUntil: 'networkidle' });
      // Wait for the Inter web font to settle — otherwise the shot can be taken
      // mid font-swap and the page height drifts a few px (see reorg investigation).
      await page.evaluate(() => document.fonts.ready.then(() => true));
      // Snap CSS transitions to their end state. `animations: 'disabled'` below does not
      // cover a transition that ZK starts client-side after Playwright has set the page up:
      // progressmeter's fill transitions width 0 -> value on first render (~0.3s, see
      // progressmeter.css), so the shot landed at a variable point and progressmeter-gallery
      // was non-reproducible run to run — three samples differed only along the 4px-tall
      // fill's antialiased leading edge. Zero duration completes any in-flight transition
      // immediately (chat D68).
      await page.addStyleTag({ content: '*{transition-duration:0s !important}' });
      // progressmeter's widget JS also steps the fill's inline width up to the value
      // (84% mid-run, 100% about 1.5s later), which transition-duration cannot stop, so
      // wait until every fill has reached its aria-valuenow. No-op on other pages.
      await page.waitForFunction(() => Array.from(document.querySelectorAll('.z-progressmeter')).every((el) => {
        const v = el.getAttribute('aria-valuenow');
        const fill = el.querySelector('.z-progressmeter-image') as HTMLElement | null;
        return v === null || !fill || fill.style.width === `${v}%`;
      }));
      const wrapper = page.locator('.z-p-8').first();
      // Every standard preview page renders the .z-p-8 wrapper; fail loudly if a
      // newly-added page uses a different shell so it gets an explicit decision
      // (add a wrapper, or add it to SKIP) rather than a silent body-sized shot.
      await expect(
        wrapper,
        `${comp}.zul has no .z-p-8 wrapper — give it one or add "${comp}" to SKIP in gallery-scan.spec.ts`
      ).toBeVisible();
      // A page with standard heading rows is shot one section at a time with an absolute
      // pixel budget (a whole-page ratio budget grows with page height and hides a 1px border).
      const sectioned = await page.locator('.z-p-8 .z-text-uppercase.z-border-bottom').count() > 0;
      if (sectioned) {
        await expectSectionShots(page, comp, SECTION_MAX_DIFF_PIXELS, {
          animations: 'disabled',
          skipTitle: UNSTABLE_SECTIONS[comp],
        });
        return;
      }
      // Flat layout: doc/screenshots/<comp>-gallery.png (single hyphenated name).
      await expect(wrapper).toHaveScreenshot(`${comp}-gallery.png`, {
        animations: 'disabled',
        // small tolerance for sub-pixel AA differences across runs
        maxDiffPixelRatio: 0.002,
      });
    });
  }
});
